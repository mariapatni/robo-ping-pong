"""The paddle end effector: its physical numbers, and how it gets into the model.

Same contract as sim/table.py and sim/ball.py - one `add_*` function handed the
MjSpec before compile, so the vendored MJCF is never edited. Nothing here imports
build123d; the geometry comes from `cad/paddle.py` via two committed artefacts:

    sim/models/paddle/paddle.stl   the visual mesh
    cad/out/paddle_props.json      mass, centre of mass, inertia

`PaddleConfig`'s defaults are those numbers, copied in so the simulator has no
CAD dependency, and `tests/test_paddle.py` fails if the two drift apart.


WHERE IT ATTACHES
-----------------

Straight onto the wrist_roll servo's horn. On the real arm the whole gripper
comes off - fixed jaw, gripper servo, moving jaw, camera mount - and the paddle's
own hub bolts to the horn with the four M3 screws that held the jaw. In the model
`add_paddle` does the same thing to the spec: it deletes the gripper's geoms,
its moving jaw (and with it the `gripper` joint and actuator), and the camera
mount, and leaves the `gripper` body - which IS the wrist_roll link, named by the
upstream model - carrying only the horn. The paddle body hangs off it with no
joint, so MuJoCo welds it to the wrist_roll link.

The arm is left with exactly the five joints of sim.arm.ARM_JOINTS, which is also
what the hardware bus will have on it.


THE PADDLE FRAME
----------------

Matches cad/paddle.py exactly, so a coordinate read off the CAD is a coordinate
here:

    x   down the roll axis, from the horn face towards the blade
    y   across the blade
    z   0 is the hitting face, +z is the back; the roll axis is at z = axis_offset

In the `gripper` body that is x = -z_g, y = -x_g, z = y_g + axis_offset. The blade
normal - the direction the ball comes from - is -z, and the `paddle_face` site
is placed on the rubber with its own z along that normal.
"""

from __future__ import annotations

import math
import struct
from dataclasses import dataclass
from functools import cached_property
from pathlib import Path

import mujoco
import numpy as np

PADDLE_BODY = "paddle"
PADDLE_MESH = "paddle"
BLADE_GEOM = "paddle_blade"
HUB_GEOM = "paddle_hub"
NECK_GEOM = "paddle_neck"
RIB_GEOM = "paddle_rib"
FACE_SITE = "paddle_face"
HOST_BODY = "gripper"  # the wrist_roll link, as the upstream model names it
GRIPPER_BODIES = ("moving_jaw_so101_v1", "camera_mount")
GRIPPER_ACTUATOR = "gripper"

MESH_PATH = Path(__file__).resolve().parent / "models" / "paddle" / "paddle.stl"

# sim.arm.HOME is not safe with a paddle on: it was chosen for a bare tip. This
# pose puts the face at (0.244, -0.014, 0.120) - the middle of the strike band,
# where the jaw-mounted paddle used to put it - blade vertical, rim 65 mm clear
# of the table. Solved with sim.pose.solve_face_pose. Same joint order as
# ARM_JOINTS.
PADDLE_HOME = np.array([0.0, -0.787, 1.372, -0.374, 0.0])


@dataclass(frozen=True)
class PaddleConfig:
    """Everything the paddle is, in SI units. Generated by cad/paddle.py.

    The mass and inertia are of the printed PLA only; the rubber sheet is bought,
    not printed, so it is a separate mass added analytically as a thin disc. See
    `mass` and `fullinertia`.
    """

    # -- blade, from cad/paddle.py -------------------------------------------
    blade_diameter: float = 0.110
    blade_thickness: float = 0.0024
    blade_centre_x: float = 0.061  # in the paddle frame: down the roll axis
    rubber_thickness: float = 0.0012
    rubber_radius: float = 0.0505  # the disc inside the trim groove

    # -- mass properties of the print, about its own centre of mass ----------
    plastic_mass: float = 0.030514
    plastic_com: tuple[float, float, float] = (0.056170, -0.000019, 0.001906)
    # MuJoCo fullinertia order: ixx, iyy, izz, ixy, ixz, iyz.
    plastic_inertia: tuple[float, float, float, float, float, float] = (
        2.121832e-05,
        2.878993e-05,
        4.940780e-05,
        -3.312046e-08,
        1.153635e-06,
        5.985850e-09,
    )
    rubber_mass: float = 0.013941

    # -- the hub, neck and rib, as boxes for collision -----------------------
    hub_thickness: float = 0.003
    hub_radius: float = 0.0125
    neck_x: tuple[float, float] = (0.003, 0.026)
    neck_width: float = 0.012
    neck_thickness: float = 0.004
    rib_width: float = 0.003
    rib_top: float = 0.009  # at the hub; the collision box keeps it full length

    # -- where it bolts on ---------------------------------------------------
    # The roll axis's height above the hitting face. The face looks along the
    # wrist_roll link's -y, the side the old jaw-mounted paddle faced.
    axis_offset: float = 0.0125

    # -- the horn left on the wrist_roll link once the gripper is gone -------
    # A Ø20 x 2.1 mm plastic disc and its M3 centre screw. Only a token: what
    # matters is that the 87 g the upstream model hangs on this link is gone.
    horn_mass: float = 0.0015
    horn_thickness: float = 0.0021
    horn_radius: float = 0.010

    # -- contact -------------------------------------------------------------
    # 0.85 is the measured ball-on-inverted-rubber figure; bare PLA is ~0.60,
    # which is why the rubber is not optional. Same spring-damper machinery as
    # TableConfig, and the paddle takes priority over the table so a paddle-ball
    # contact uses these numbers and not the table's 0.88.
    restitution: float = 0.85
    contact_omega: float = 1000.0
    # Rubber grips: much higher sliding friction than the table's 0.25, and it is
    # what will eventually put spin on the ball.
    friction: tuple[float, float, float] = (0.9, 0.005, 0.0001)
    priority: int = 2

    # White PLA, as it actually printed (it was meant to be black). The face
    # is a shade greyer only so it can be told from the back in a render.
    # Matters for vision, not for the policy: the cameras are monochrome, and
    # an orange ball reads darker against white than it did against black.
    rgba: tuple[float, float, float, float] = (0.93, 0.93, 0.92, 1.0)
    face_rgba: tuple[float, float, float, float] = (0.85, 0.85, 0.84, 1.0)

    # -- derived -------------------------------------------------------------

    @property
    def blade_radius(self) -> float:
        return 0.5 * self.blade_diameter

    @property
    def mass(self) -> float:
        """Print plus rubber: what the arm actually has to carry."""
        return self.plastic_mass + self.rubber_mass

    @property
    def rubber_com(self) -> np.ndarray:
        """Centre of the rubber disc, glued to the z = 0 face and so at -t/2."""
        return np.array([self.blade_centre_x, 0.0, -0.5 * self.rubber_thickness])

    @cached_property
    def com(self) -> np.ndarray:
        """Centre of mass of print + rubber, in the paddle frame."""
        m1, m2 = self.plastic_mass, self.rubber_mass
        return (m1 * np.asarray(self.plastic_com) + m2 * self.rubber_com) / (m1 + m2)

    @cached_property
    def inertia(self) -> np.ndarray:
        """Inertia tensor of print + rubber about `com`, as a 3x3, in kg m^2.

        The rubber is a thin disc about the blade normal (local z), so its own
        tensor is diagonal with Izz = mR^2/2 and Ixx = Iyy = mR^2/4 + mt^2/12;
        both parts are then parallel-axis shifted onto the combined centre.
        """
        ixx, iyy, izz, ixy, ixz, iyz = self.plastic_inertia
        i1 = np.array([[ixx, ixy, ixz], [ixy, iyy, iyz], [ixz, iyz, izz]])

        m2, r2, t2 = self.rubber_mass, self.rubber_radius, self.rubber_thickness
        i2 = np.diag(
            [
                0.25 * m2 * r2 * r2 + m2 * t2 * t2 / 12.0,
                0.25 * m2 * r2 * r2 + m2 * t2 * t2 / 12.0,
                0.5 * m2 * r2 * r2,
            ]
        )

        def shift(m: float, d: np.ndarray) -> np.ndarray:
            return m * (float(d @ d) * np.eye(3) - np.outer(d, d))

        c = self.com
        return (
            i1
            + shift(self.plastic_mass, np.asarray(self.plastic_com) - c)
            + i2
            + shift(m2, self.rubber_com - c)
        )

    @property
    def fullinertia(self) -> tuple[float, ...]:
        """`inertia` in MuJoCo's fullinertia order."""
        m = self.inertia
        return (m[0, 0], m[1, 1], m[2, 2], m[0, 1], m[0, 2], m[1, 2])

    @property
    def contact_damping_ratio(self) -> float:
        e = min(max(self.restitution, 1e-3), 0.999)
        r = -math.log(e) / math.pi
        return r / math.sqrt(1.0 + r * r)

    @property
    def contact_solref(self) -> tuple[float, float]:
        w = self.contact_omega
        return (-w * w, -2.0 * self.contact_damping_ratio * w)

    # -- the attachment frame -------------------------------------------------

    @cached_property
    def frame(self) -> tuple[np.ndarray, np.ndarray]:
        """(position, 3x3 rotation) of the paddle frame in the `gripper` body.

        The horn face is the body's z = 0 plane and the roll axis its z axis, so
        the paddle frame is that axis turned to point down the paddle, dropped
        `axis_offset` to the hitting face.
        """
        rot = np.column_stack(
            [
                [0.0, 0.0, -1.0],  # x: down the roll axis, away from the horn
                [-1.0, 0.0, 0.0],  # y: across the blade
                [0.0, 1.0, 0.0],  # z: from the hitting face to the back
            ]
        )
        return np.array([0.0, -self.axis_offset, 0.0]), rot

    @property
    def quat(self) -> np.ndarray:
        """`frame`'s rotation as a MuJoCo (w, x, y, z) quaternion."""
        q = np.zeros(4)
        mujoco.mju_mat2Quat(q, self.frame[1].reshape(9))
        return q

    @property
    def face_pos(self) -> np.ndarray:
        """Centre of the rubber face, in the paddle frame."""
        return np.array([self.blade_centre_x, 0.0, -self.rubber_thickness])


# -- the mesh -----------------------------------------------------------------


def read_stl(path: Path = MESH_PATH) -> tuple[np.ndarray, np.ndarray]:
    """Vertices (n, 3) in millimetres and triangles (m, 3) from a binary STL.

    Written here rather than pulled from a mesh library so that sim/ keeps its
    two-package dependency footprint. Vertices are welded on a 1 um grid: an STL
    repeats every vertex once per face, and MuJoCo would otherwise be handed
    three times the vertices it needs and shade the part faceted.
    """
    raw = path.read_bytes()
    n = int(struct.unpack("<I", raw[80:84])[0])
    rec = np.frombuffer(raw[84 : 84 + n * 50], dtype=np.uint8).reshape(n, 50)
    tri = rec[:, 12:48].copy().view("<f4").reshape(n, 3, 3).astype(np.float64)
    verts, inv = np.unique(np.round(tri.reshape(-1, 3), 3), axis=0, return_inverse=True)
    return verts, inv.reshape(-1, 3).astype(np.int32)


# -- the spec edit ------------------------------------------------------------


def add_paddle(spec: mujoco.MjSpec, cfg: PaddleConfig | None = None,
               prefix: str = "") -> mujoco.MjSpec:
    """Take the gripper off and bolt the paddle onto the wrist_roll horn, rigidly.

    The visual is the CAD mesh; collision is a cylinder and three boxes, because
    a 2.7 g ball on a 900-triangle mesh is exactly the contact MuJoCo is worst
    at, and the blade is a cylinder to within a tenth of a millimetre anyway. The
    cylinder is grown by `rubber_thickness` on the hitting side so the contact
    surface is the rubber, which is what the ball actually touches.
    """
    cfg = cfg or PaddleConfig()
    pos, _ = cfg.frame
    remove_gripper(spec, cfg, prefix)

    # The mesh is an asset, not a body, so two arms share one copy. Adding it
    # again under a second prefix is a duplicate-name error, and duplicating
    # the geometry would be wasteful anyway.
    if not any(m.name == PADDLE_MESH for m in spec.meshes):
        verts, faces = read_stl()
        mesh = spec.add_mesh()
        mesh.name = PADDLE_MESH
        mesh.uservert = verts.reshape(-1).tolist()
        mesh.userface = faces.reshape(-1).tolist()
        mesh.scale = [1e-3, 1e-3, 1e-3]  # the CAD is in millimetres

    # `prefix` lets a second arm, attached under its own prefix, carry its own
    # paddle: MjSpec.attach renames every body, so the host and the paddle's
    # own names both have to be qualified.
    host = spec.body(prefix + HOST_BODY)
    body = host.add_body(name=prefix + PADDLE_BODY, pos=pos.tolist(), quat=cfg.quat.tolist())
    # No joint: MuJoCo welds it to the wrist_roll link, which is the whole point.
    body.explicitinertial = True
    body.mass = cfg.mass
    body.ipos = cfg.com.tolist()
    body.fullinertia = list(cfg.fullinertia)

    body.add_geom(
        name=prefix + f"{PADDLE_BODY}_visual",
        type=mujoco.mjtGeom.mjGEOM_MESH,
        meshname=PADDLE_MESH,
        mass=0.0,  # the body's explicit inertial owns all of it
        contype=0,
        conaffinity=0,
        group=2,
        rgba=list(cfg.rgba),
    )

    # The rubber, drawn only. Its mass is already in the body's inertial.
    body.add_geom(
        name=prefix + f"{PADDLE_BODY}_rubber",
        type=mujoco.mjtGeom.mjGEOM_CYLINDER,
        pos=[cfg.blade_centre_x, 0.0, -0.5 * cfg.rubber_thickness],
        size=[cfg.rubber_radius, 0.5 * cfg.rubber_thickness, 0.0],
        mass=0.0,
        contype=0,
        conaffinity=0,
        group=2,
        rgba=list(cfg.face_rgba),
    )

    half = 0.5 * (cfg.blade_thickness + cfg.rubber_thickness)
    body.add_geom(
        name=prefix + BLADE_GEOM,
        type=mujoco.mjtGeom.mjGEOM_CYLINDER,
        pos=[cfg.blade_centre_x, 0.0, 0.5 * (cfg.blade_thickness - cfg.rubber_thickness)],
        size=[cfg.blade_radius, half, 0.0],
        mass=0.0,
        condim=3,
        friction=list(cfg.friction),
        solref=list(cfg.contact_solref),
        priority=cfg.priority,
        group=3,
        rgba=[1.0, 0.0, 0.0, 0.3],
    )
    # Hub, neck web and rib. The rib tapers on the print; its box does not, which
    # errs towards the safety check seeing a little more paddle than there is.
    ax, w, t = cfg.axis_offset, cfg.neck_width, cfg.neck_thickness
    x0, x1 = cfg.neck_x
    boxes = {
        HUB_GEOM: ((0.0, cfg.hub_thickness), cfg.hub_radius, (0.0, ax + cfg.hub_radius)),
        NECK_GEOM: ((x0, x1), 0.5 * w, (0.0, t)),
        RIB_GEOM: ((x0, x1), 0.5 * cfg.rib_width, (t, cfg.rib_top)),
    }
    for name, ((bx0, bx1), half_y, (bz0, bz1)) in boxes.items():
        body.add_geom(
            name=prefix + name,
            type=mujoco.mjtGeom.mjGEOM_BOX,
            pos=[0.5 * (bx0 + bx1), 0.0, 0.5 * (bz0 + bz1)],
            size=[0.5 * (bx1 - bx0), half_y, 0.5 * (bz1 - bz0)],
            mass=0.0,
            condim=3,
            friction=list(cfg.friction),
            solref=list(cfg.contact_solref),
            priority=cfg.priority,
            group=3,
            rgba=[1.0, 0.0, 0.0, 0.3],
        )

    # The face frame. Rotated 180 deg about the paddle's x so that the site's own
    # z is the outward face normal - i.e. site_xmat[:, 2] is where the ball has to
    # come from - while its x still runs down the paddle towards the blade.
    body.add_site(
        name=prefix + FACE_SITE,
        pos=cfg.face_pos.tolist(),
        quat=[0.0, 1.0, 0.0, 0.0],
        group=3,
    )

    return spec


def remove_gripper(spec: mujoco.MjSpec, cfg: PaddleConfig | None = None,
                   prefix: str = "") -> None:
    """Strip the wrist_roll link back to its horn, as on the hardware.

    Deletes every geom on the link (the fixed jaw, the gripper servo and their
    colliders), the moving jaw - which takes the `gripper` joint with it - its
    actuator, and the camera mount and its camera. The link's 87 g upstream
    inertial is replaced by the horn alone; the paddle brings its own.
    """
    cfg = cfg or PaddleConfig()
    act = spec.actuator(prefix + GRIPPER_ACTUATOR)
    if act is not None:  # before its joint goes, or MuJoCo drops it for us
        spec.delete(act)
    for name in GRIPPER_BODIES:
        child = spec.body(prefix + name)
        if child is not None:
            spec.delete(child)

    host = spec.body(prefix + HOST_BODY)
    for geom in list(host.geoms):
        spec.delete(geom)

    m, r, h = cfg.horn_mass, cfg.horn_radius, cfg.horn_thickness
    host.explicitinertial = True
    host.mass = m
    host.ipos = [0.0, 0.0, 0.5 * h]
    ixx = m * (3.0 * r * r + h * h) / 12.0
    host.fullinertia = [ixx, ixx, 0.5 * m * r * r, 0.0, 0.0, 0.0]
    host.add_geom(
        name=prefix + "wrist_horn",
        type=mujoco.mjtGeom.mjGEOM_CYLINDER,
        pos=[0.0, 0.0, 0.5 * h],
        size=[r, 0.5 * h, 0.0],
        mass=0.0,
        contype=0,
        conaffinity=0,
        group=2,
        rgba=[0.1, 0.1, 0.1, 1.0],
    )


# -- reading it back ----------------------------------------------------------


def face_pose(model: mujoco.MjModel, data: mujoco.MjData) -> tuple[np.ndarray, np.ndarray]:
    """(centre, outward normal) of the hitting face in world coordinates.

    This is the pose a controller aims: put the centre where the ball will be and
    point the normal where the ball should go. `mj_forward` or `mj_step` must have
    run since the last qpos change.
    """
    sid = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_SITE, FACE_SITE)
    if sid < 0:
        raise KeyError(f"site {FACE_SITE!r} not in model - was add_paddle called?")
    return data.site_xpos[sid].copy(), data.site_xmat[sid].reshape(3, 3)[:, 2].copy()
